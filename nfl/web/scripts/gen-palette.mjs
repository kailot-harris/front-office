#!/usr/bin/env node
/**
 * Generates app/palette.css: the Tailwind palettes this app uses, as RGB channel
 * variables that follow prefers-color-scheme (front-office issue 6 for NFL).
 *
 * The app was written dark-only, so every component already says "text-slate-100
 * on a dark surface". Rather than add a dark: variant to ~2,000 class names, each
 * shade is a variable: dark mode keeps Tailwind's stock value, light mode swaps it
 * for the mirrored shade (slate-100 text -> slate-900 text, slate-800 panel ->
 * slate-200 panel, emerald-400 text -> emerald-700 text) so contrast holds both ways.
 * Surfaces and the accent come straight from the --fo-* tokens instead.
 *
 * Run: node scripts/gen-palette.mjs   (keep PALETTES in sync with tailwind.config.ts)
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const colors = require('tailwindcss/colors');

const PALETTES = ['slate', 'emerald', 'amber', 'cyan', 'rose', 'red', 'blue', 'indigo', 'purple', 'teal', 'sky', 'orange', 'green', 'yellow'];
const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

// Light-mode replacement shade for each dark-mode shade.
const LIGHT_NEUTRAL = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 600, 500: 600, 600: 500, 700: 300, 800: 200, 900: 100, 950: 50 };
const LIGHT_CHROMA = { 50: 950, 100: 900, 200: 800, 300: 800, 400: 800, 500: 700, 600: 800, 700: 700, 800: 200, 900: 100, 950: 50 };
// The app's emerald accent scale (tailwind.config.ts `accent`).
const ACCENT = { 50: '#ecfdf5', 400: '#34d399', 500: '#10b981', 600: '#047857', 700: '#047857', 900: '#064e3b', 950: '#022c22' };
const ACCENT_LIGHT = { 50: '#022c22', 400: '#047857', 500: '#047857', 600: '#047857', 700: '#065f46', 900: '#d1fae5', 950: '#ecfdf5' };

const rgb = (hex) => {
  const n = parseInt(hex.slice(1), 16);
  return `${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255}`;
};

function block(light) {
  const out = [];
  for (const p of PALETTES) {
    const map = p === 'slate' ? LIGHT_NEUTRAL : LIGHT_CHROMA;
    for (const s of SHADES) out.push(`  --c-${p}-${s}: ${rgb(colors[p][light ? map[s] : s])};`);
  }
  for (const [s, hex] of Object.entries(light ? ACCENT_LIGHT : ACCENT)) out.push(`  --c-accent-${s}: ${rgb(hex)};`);
  // Dark mode: slate-500/600 are used as small muted text, which fails AA on the
  // dark surfaces at stock values, so they are lifted just enough to pass.
  if (!light) {
    out.push('  --c-slate-500: 148 163 184;');
    out.push('  --c-slate-600: 123 136 156;');
  }
  out.push(`  --c-white: ${rgb(light ? colors.slate[900] : '#ffffff')};`);
  out.push(`  --c-black: ${rgb(light ? '#ffffff' : '#000000')};`);
  return out.join('\n');
}

{
  const css = `/* GENERATED by scripts/gen-palette.mjs. Do not edit by hand. */
/* Dark is the default; light is prefers-color-scheme: light. */
:root {
${block(false)}
}

@media (prefers-color-scheme: light) {
  :root {
${block(true).replace(/^/gm, '  ')}
  }
}
`;
  fs.writeFileSync(path.join(import.meta.dirname, '..', 'app', 'palette.css'), css);
  console.log('wrote app/palette.css');
}
