import React from 'react';
import { Metadata } from 'next';
import fs from 'fs';
import path from 'path';
import { MatchupsPayload } from '@/lib/matchupTypes';
import { MatchupsClient } from '@/components/MatchupsClient';

export const metadata: Metadata = {
  title: 'Matchups | WNBA Analytics',
  description:
    'Per-game WNBA matchups by week: model projections for upcoming games, final scores for played games, and graded predictions where the model logged one.',
};

// Written by the repo root's build_matchups_dataset.R (issue #74).
async function getMatchupsData(): Promise<MatchupsPayload | null> {
  try {
    const filePath = path.join(process.cwd(), 'public', 'data', 'matchups_slates.json');

    if (!fs.existsSync(filePath)) {
      return null;
    }

    return JSON.parse(fs.readFileSync(filePath, 'utf8')) as MatchupsPayload;
  } catch (err) {
    console.error('Failed to load matchups data:', err);
    return null;
  }
}

export default async function MatchupsPage() {
  const data = await getMatchupsData();

  // `null` means the payload is absent or unreadable, which is a different
  // state from "present but nothing graded yet" -- the client renders the
  // latter from the payload's own grading_state. Keep them distinct.
  if (!data) {
    return (
      <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-8">
        <div className="relative pb-6 mb-4">
          <h1 className="text-3xl font-bold text-white">
            <span className="text-accent-400">WNBA</span> Matchups
          </h1>
          <div className="absolute bottom-0 left-0 right-0 h-[2px] bg-gradient-to-r from-violet-400 via-violet-500/40 to-transparent" />
        </div>
        <div className="rounded-lg border border-slate-700 bg-slate-800/50 p-6">
          <p className="text-slate-300">
            No matchups dataset is available yet.
          </p>
          <p className="text-slate-400 text-sm mt-2">
            It is generated by{' '}
            <code className="text-slate-300">build_matchups_dataset.R</code>, the
            final stage of the analytics pipeline.
          </p>
        </div>
      </div>
    );
  }

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-8">
      <MatchupsClient data={data} />
    </div>
  );
}
